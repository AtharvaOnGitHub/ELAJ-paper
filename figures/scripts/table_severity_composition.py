"""Supplementary table: cell-family composition against surgical severity,
patients only (X8e, axw1008 src/scripts/composition_by_disease.py).
Writes supplementary/tables/severity_composition.tex from x8_x9_composition.csv."""
from pathlib import Path
import pandas as pd
ROOT = Path(__file__).resolve().parents[2]
CSV = ROOT.parent / "axw1008/docs/paper/x8_x9_composition.csv"
c = pd.read_csv(CSV)
c = c[c.contrast == "severity_low_vs_high"].set_index("family").loc[["immune", "stromal", "epithelial", "endothelial"]]
n = int(c.n_donors.iloc[0]); assert (c.n_donors == n).all()
rows = "\n".join(f"{f} & {r.mean_low:.4f} & {r.mean_high:.4f} & {r.F:.3f} & {r.p:.4f} \\\\" for f, r in c.iterrows())
(ROOT / "supplementary/tables/severity_composition.tex").write_text(
    "% GENERATED by figures/scripts/table_severity_composition.py. Do not edit.\n"
    "\\begin{tabular}{@{}lrrrr@{}}\n\\toprule\n"
    "family & mean share, low & mean share, high & $F$ & \\textit{P} \\\\\n\\midrule\n"
    f"{rows}\n\\bottomrule\n\\end{{tabular}}\n")
print(f"{n} patients"); print(c[["mean_low", "mean_high", "F", "p"]])
