"""Tables for the Supplementary Methods, generated, never typed.

    /Users/atharvawaghmare/miniconda3/envs/elaj/bin/python figures/scripts/supp_methods.py

Writes supplementary/tables/hyperparameters.tex from the reported model's own
resolved configuration (run_config.json, every value the run actually used)
and its training log (parameter count, selected epoch), so the table cannot
drift from the run. AW, 15 Nov: "Training hyperparameters, with a table".

Writes supplementary/tables/buckets.tex, the size-bucket plan, by running the
model's own `plan_buckets` (pulled out of bucketing.py with ast, so no torch
is needed) on the group sizes of the model's own vocabulary, and asserts the
result against the plan the training log printed. AW, 18 Nov: "Gene group
bucketing was supposed to be explained in detail".
"""
from __future__ import annotations

import ast
import json
import re
from collections import Counter
from pathlib import Path

import pandas as pd

ROOT = Path("/Users/atharvawaghmare/Endo research/ELAJ")
RUN = ROOT / "Outputs/p_series/p1_dab168_kl1"
TAB = Path(__file__).resolve().parents[2] / "supplementary" / "tables"
SRC = ROOT / "axw1008" / "src"
BUCKETING = SRC / "endo_model/model/encoders/batched/bucketing.py"
VOCAB = SRC / "data" / "vocabulary_v1.json"      # the file run_config names


def _plan_buckets():
    """`plan_buckets` and `SizeBucket` exactly as the model runs them, taken
    from the module's source so this script needs no torch."""
    tree = ast.parse(BUCKETING.read_text())
    keep = [n for n in tree.body
            if isinstance(n, (ast.ClassDef, ast.FunctionDef))
            and n.name in ("SizeBucket", "plan_buckets")]
    mod = ast.Module(body=[ast.parse("from __future__ import annotations\n"
                                     "from dataclasses import dataclass").body[1]] + keep,
                     type_ignores=[])
    ns: dict = {}
    exec(compile(ast.fix_missing_locations(mod), str(BUCKETING), "exec"), ns)
    return ns["plan_buckets"]


def buckets(c: dict, log: str) -> None:
    ge = c["model"]["group_encoder"]
    assert Path(c["data"]["vocabulary_path"]).name == VOCAB.name, c["data"]["vocabulary_path"]
    sizes = dict(Counter(v["group"] for v in json.load(open(VOCAB)).values()))
    n_cls = int(ge["n_cls"])
    plan = _plan_buckets()
    seq = {g: n + n_cls for g, n in sizes.items()}
    ideal = sum(x * x for x in seq.values())

    def pad_share(bs):
        work = sum(b.attention_work for b in bs)
        return 100 * (work - ideal) / work

    rep = plan(sizes, ge["n_buckets"], n_cls=n_cls)
    # The plan the run itself printed at build time. Must match exactly.
    logged = re.search(r"in (\d+) buckets \(lengths \[([\d, ]+)\]\)", log)
    assert int(logged.group(1)) == len(rep), logged.group(0)
    assert [int(x) for x in logged.group(2).split(",")] == [b.seq_len for b in rep], logged.group(0)

    L = [r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
         r"Bucket & Groups & Genes per group & Padded length & Arithmetic on padding \\",
         r"\midrule"]
    for i, b in enumerate(rep, 1):
        g = sorted(sizes[n] for n in b.names)
        own = 100 * (b.attention_work - sum(seq[n] ** 2 for n in b.names)) / b.attention_work
        L.append(rf"\quad {i} & {len(g)} & {g[0]}--{g[-1]} & {b.seq_len} & {own:.1f}\% \\")
    one = plan(sizes, 1, n_cls=n_cls)
    L += [r"\addlinespace",
          rf"\quad All {len(rep)} buckets & {len(sizes)} & {min(sizes.values())}--{max(sizes.values())} & & {pad_share(rep):.1f}\% \\",
          rf"\quad One block, for comparison & {len(sizes)} & {min(sizes.values())}--{max(sizes.values())} & {one[0].seq_len} & {pad_share(one):.1f}\% \\",
          r"\midrule",
          r"\multicolumn{5}{@{}l}{\textit{Other bucket counts}} \\"]
    for k in (2, 3, 5, 6, 8):
        L.append(rf"\quad {k} buckets & & & & {pad_share(plan(sizes, k, n_cls=n_cls)):.1f}\% \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    (TAB / "buckets.tex").write_text(
        "% GENERATED by figures/scripts/supp_methods.py from bucketing.plan_buckets\n"
        "% and vocabulary_v1.json; asserted against the training log. Do not edit.\n"
        + "\n".join(L) + "\n")
    print(f"wrote {TAB / 'buckets.tex'}: lengths {[b.seq_len for b in rep]}, "
          f"padding {pad_share(one):.1f}% -> {pad_share(rep):.1f}%")


def main() -> None:
    c = json.load(open(RUN / "run_config.json"))
    M, T, D = c["model"], c["training"], c["data"]
    log = (RUN / "train_57935604.log").read_text()
    n_params = re.search(r"Model parameters: ([\d,]+)", log).group(1)
    met = pd.read_csv(RUN / "metrics.csv")
    best = met.loc[met.val_nb.idxmin()]
    assert int(best.epoch) == 4, best.epoch            # the checkpoint every number uses

    def f(x):
        return f"{x:g}" if isinstance(x, float) else str(x)

    rows = [
        ("Input", None),
        ("Count scaling", "log, library size scaled to " + f"{int(M['tokens']['target_sum']):,}".replace(",", "{,}")),
        ("Value encoding", "one learned direction per gene, scaled by its count"),
        ("Token width $d$", f(M["d_token"])),
        ("Genes, groups", f"15{{,}}496 genes in {M['n_groups']} groups"),
        ("Measured genes shown to the encoder", f"{T['gene_mask_target']:,} per cell, in training".replace(",", "{,}", 1)),
        ("Gene encoder", None),
        ("Transformer layers per group", f(M["group_encoder"]["n_layers"])),
        ("Attention heads", f(M["group_encoder"]["n_heads"])),
        ("Dropout", f(M["group_encoder"]["dropout"])),
        ("Summary tokens per group", "9 (1 learned, 8 pooled statistics)"),
        ("Size buckets", f(M["group_encoder"]["n_buckets"])),
        ("Cell encoder", None),
        ("Transformer layers", f(M["aggregation_encoder"]["n_layers"])),
        ("Attention heads", f(M["aggregation_encoder"]["n_heads"])),
        ("Dropout", f(M["aggregation_encoder"]["dropout"])),
        ("Width $d_{\\mathrm{agg}}$", f(M["d_agg"])),
        ("Latent", None),
        ("Gaussian dimensions", f(M["d_gauss"])),
        ("Circular dimensions", f(M["n_circular"])),
        ("Decoder", None),
        ("Width $d_{\\mathrm{dec}}$", f(M["d_dec"])),
        ("Tissue, platform, study embeddings", f"{M['d_tissue']}, {M['d_platform']}, {M['d_study']} dimensions"),
        # THE VALUE IN FORCE, NOT THE STORED ONE. run_config records 0.25 under
        # model.drain, but EndoFoundationModel applies it only when the drain is
        # enabled, and it was not: train_blanked_covariates is 0.0 every epoch.
        ("Disease embedding", "none" if M["d_disease"] == 0 else f(M["d_disease"])),
        ("Covariates zeroed per step", f"probability {f(M['drain']['blank_covariates_p'])}"
         if M["drain"]["enabled"] else "never"),
        ("Objective", None),
        ("Reconstruction weight $w_{\\mathrm{nb}}$", f(M["loss"]["w_nb"])),
        ("KL weight $w_{\\mathrm{kl}}$", f(M["loss"]["w_kl_gauss"])),
        ("KL ramp", f"0 to {f(T['kl_annealing']['beta_max'])} over the first "
                    f"{int(T['kl_annealing']['warmup_fraction'] * 100)}\\% of steps"),
        ("KL free bits", f(M["loss"]["free_bits"])),
        ("Adversary weight $w_{\\mathrm{dab}}$, reversal $\\lambda_{\\mathrm{dab}}$",
         f"{f(M['loss']['w_dab'])}, {f(M['dab']['lambda_dab'])}"),
        ("Adversary network", f"{M['dab']['n_layers']} layers, {M['dab']['hidden_dim']} hidden units"),
        ("Phase head weight, label smoothing",
         f"{f(M['loss']['w_cls'])}, {f(M['classifier']['label_smoothing'])}"),
        ("Cell-similarity weight, threshold",
         f"{f(M['loss']['w_ecs'])}, {f(M['ecs']['threshold'])}"),
        ("Optimisation", None),
        ("Optimiser", f"{T['optimizer']['name']}, $\\beta = ({T['optimizer']['betas'][0]}, {T['optimizer']['betas'][1]})$"),
        ("Learning rate, weight decay", "$10^{-3}$, $10^{-4}$" if (T['optimizer']['lr'], T['optimizer']['weight_decay']) == (0.001, 0.0001)
         else f"{f(T['optimizer']['lr'])}, {f(T['optimizer']['weight_decay'])}"),
        ("Schedule", f"cosine over {T['max_epochs']} epochs"),
        ("Batch size", f(T["batch_size"])),
        ("Gradient clipping", f"norm {f(T['grad_clip_norm'])}"),
        ("Precision", "bf16"),
        ("Early stopping", f"held-out reconstruction, patience {T['early_stop_patience']} "
                           f"after {T['early_stop_warmup_epochs']} epochs"),
        ("Selected epoch", f"{int(best.epoch)} (held-out reconstruction {best.val_nb:.4f})"),
        ("Data", None),
        ("Split", f"by donor, {int(100 - 100 * (D['splits']['val_fraction'] + D['splits']['test_fraction']))}/"
                  f"{int(100 * D['splits']['val_fraction'])}/{int(100 * D['splits']['test_fraction'])}, seed {D['splits']['seed']}"),
        ("Training seed", f(c["experiment"]["seed"])),
        ("Parameters", n_params.replace(",", "{,}")),
    ]
    L = [r"\begin{tabular}{@{}ll@{}}", r"\toprule", r"Setting & Value \\", r"\midrule"]
    first = True
    for k, v in rows:
        if v is None:
            if not first:
                L.append(r"\addlinespace")
            L.append(rf"\multicolumn{{2}}{{@{{}}l}}{{\textit{{{k}}}}} \\")
            first = False
        else:
            L.append(rf"\quad {k} & {v} \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    TAB.mkdir(parents=True, exist_ok=True)
    (TAB / "hyperparameters.tex").write_text(
        "% GENERATED by figures/scripts/supp_methods.py from run_config.json. Do not edit.\n"
        + "\n".join(L) + "\n")
    print(f"wrote {TAB / 'hyperparameters.tex'} ({sum(v is not None for _, v in rows)} settings)")
    buckets(c, log)


if __name__ == "__main__":
    main()
